  static String get signin => Env.isDev ? Env.signin : Env.signinLive;
  /// …/user/signin/android/verify: trades the emailed sign-in code for the app token (PRD #22)
  static String get signinVerify => '${signin.replaceFirst(RegExp(r'/+$'), '')}/verify';
  /// sibling of signin (…/user/signin/android -> …/user/tv/link): the phone approves a TV code here
  static String get tvLink => signin.replaceFirst(RegExp(r'/signin/android$'), '/tv/link');
  /// sibling of signin: the signed phone<->TV remote room token for the sockets relay (PRD #12)
  static String get remoteToken => signin.replaceFirst(RegExp(r'/signin/android$'), '/remote/token/android');
  /// the user service's /earn routes (…/user/signin/android -> …/earn): watch ads for credits (PRD #15)
  static String get earn {
    final m = RegExp(r'^(.*)/user/signin/android$').firstMatch(signin);
    return m == null ? '' : '${m[1]}/earn';
  }
  static String get signout => Env.isDev ? Env.signout : Env.signoutLive;
  /// siblings of signin (…/user/signin/android): recently watched runs on the app token,
  /// neighbors is the public route the web uses
  static String get recent => signin.replaceFirst(RegExp(r'/signin/android$'), '/recent/android');
  static String get neighbors => signin.replaceFirst(RegExp(r'/signin/android$'), '/neighbors');
  /// The user service's /profile router sits beside /user (…/user/signin/android -> …/profile/…).
  /// GET/POST /profile/android - phone + country/county/ward on the app token (movies PRD #6, #7).
  static String get profile => signin.replaceFirst(RegExp(r'/user/signin/android$'), '/profile/android');
  /// The user service's /sales router (`…/user/signin/android` -> `…/sales/<path>/android`): selling downloaded
  /// videos phone to phone (movies PRD #10). [path] like 'offer' -> …/sales/offer/android.
  static String sales(String path) {
    final m = RegExp(r'^(.*)/user/signin/android$').firstMatch(signin);
    return m == null ? '' : '${m[1]}/sales/$path/android';
  }
  /// GET /profile/locations - countries (dialling code, plays), Kenya's counties, ward suggestions. No auth.
  static String get profileLocations =>
      signin.replaceFirst(RegExp(r'/user/signin/android$'), '/profile/locations');
  /// The user service's /comments router (movies PRD #4), beside /profile. {type, id, eden, page}
  /// lists (no sign-in; the app token only marks the caller's own), add/remove need the app token.
  static String get commentsList => signin.replaceFirst(RegExp(r'/user/signin/android$'), '/comments/list/android');
  static String get commentsAdd => signin.replaceFirst(RegExp(r'/user/signin/android$'), '/comments/add/android');
  static String get commentsRemove =>
      signin.replaceFirst(RegExp(r'/user/signin/android$'), '/comments/remove/android');
  /// The user service's /reels router (movies PRD #26): likes + comments on Eden mini-series reels.
  /// [route] is stats | like | comments | comment | comment/remove -> `…/reels/<route>/android` ('' if unset).
  static String reels(String route) {
    final m = RegExp(r'^(.*)/user/signin/android$').firstMatch(signin);
    return m == null ? '' : '${m[1]}/reels/$route/android';
  }
  /// The reactions service (movies PRD #11): base URL of its API + socket.io server, and one of its routes
  /// (create | live | info | join | token | end). It takes the app token as Bearer.
  static String get reactionsBase => Env.isDev ? Env.reactionsApi : Env.reactionsApiLive;
  static String reactions(String route) => '$reactionsBase/reactions/$route';
  static String get shopPostAd => Env.isDev ? Env.shopPostAd : Env.shopPostAdLive;
  static String get eden => Env.isDev ? Env.eden : Env.edenLive;
  /// POST {image} -> the studio image's bytes; only takes `<studio>/images/...` paths.
  static String get edenPoster => '${Env.isDev ? Env.edenApi : Env.edenApiLive}/cinema/poster';
  /// POST /database/eden/episodes {id} - every episode of one Eden series.
  static String get edenEpisodes =>
      checkUrl.isEmpty ? '' : checkUrl.replaceFirst(RegExp(r'/check-url$'), '/eden/episodes');
}
