/// Picks the dev or *_LIVE value exactly like the RN code's
/// `ENVIRONMENT === "development" ? X : X_LIVE` ternaries.
class Api {
  Api._();

  static String get insertPlaylist => Env.isDev ? Env.insertPlaylist : Env.insertPlaylistLive;
  static String get playlistSelect => Env.isDev ? Env.playlistSelect : Env.playlistSelectLive;
  static String get followers => Env.isDev ? Env.followers : Env.followersLive;
  static String get followersSelect => Env.isDev ? Env.followersSelect : Env.followersSelectLive;
  static String get checkUrl => Env.isDev ? Env.checkUrl : Env.checkUrlLive;
  /// POST /database/videos - lives beside check-url on the database service.
  static String get videos => checkUrl.isEmpty ? '' : checkUrl.replaceFirst(RegExp(r'/check-url$'), '/videos');
  /// POST /database/people/eden - Eden studios' people, most followed first.
  static String get edenPeople => checkUrl.isEmpty ? '' : checkUrl.replaceFirst(RegExp(r'/check-url$'), '/people/eden');
  /// POST /database/people/eden/id - one Eden person's profile, credits, resume reel and studio mates.
  static String get edenPerson => checkUrl.isEmpty ? '' : checkUrl.replaceFirst(RegExp(r'/check-url$'), '/people/eden/id');
  /// POST /user/eden/follow/android {person_id} - follow an Eden person as the signed-in viewer.
  /// Beside /user/authentication/android on the user service; the app token names the viewer.
  static String get edenFollow => apiUrl.replaceFirst(RegExp(r'/authentication/android$'), '/eden/follow/android');
  /// POST /user/eden/following/android {person_id} - does the signed-in viewer follow them?
  static String get edenFollowing => apiUrl.replaceFirst(RegExp(r'/authentication/android$'), '/eden/following/android');
  /// POST /user/eden/unfollow/android {person_id} - stop following an Eden person.
  static String get edenUnfollow => apiUrl.replaceFirst(RegExp(r'/authentication/android$'), '/eden/unfollow/android');
  static String get host => Env.isDev ? Env.host : Env.hostLive;
  static String get search => Env.isDev ? Env.search : Env.searchLive;
  static String get searchInsert => Env.isDev ? Env.searchInsert : Env.searchInsertLive;
  static String get searchPerson => Env.isDev ? Env.searchPerson : Env.searchPersonLive;
  static String get searchInsertPerson => Env.isDev ? Env.searchInsertPerson : Env.searchInsertPersonLive;
  /// POST /database/search/eden - LIKE search of Eden titles, beside the TMDB search cache routes.
  static String get edenSearch => search.isEmpty ? '' : search.replaceFirst(RegExp(r'/search/fetch/?$'), '/search/eden');
  static String get stream => Env.isDev ? Env.stream : Env.streamLive;
  static String get play => Env.isDev ? Env.play : Env.playLive;
  static String get subPlaying => Env.isDev ? Env.subPlaying : Env.subPlayingLive;
  static String get hostPlay => Env.isDev ? Env.hostPlay : Env.hostPlayLive;
