  static String get insertLikes => Env.isDev ? Env.insertLikes : Env.insertLikesLive;
  static String get removeLikes => Env.isDev ? Env.removeLikes : Env.removeLikesLive;
  static String get report => Env.isDev ? Env.report : Env.reportLive;
  static String get checkUserCredits => Env.isDev ? Env.checkUserCredits : Env.checkUserCreditsLive;
  static String get updateUserCredits => Env.isDev ? Env.updateUserCredits : Env.updateUserCreditsLive;
  static String get payUserCredits => Env.isDev ? Env.payUserCredits : Env.payUserCreditsLive;
  static String get userPaid => Env.isDev ? Env.userPaid : Env.userPaidLive;
  static String get apiUrl => Env.isDev ? Env.apiUrl : Env.apiUrlLive;
  static String get email => Env.isDev ? Env.email : Env.emailLive;
